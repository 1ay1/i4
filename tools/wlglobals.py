#!/usr/bin/env python3
"""wlglobals — list every interface a compositor would advertise as a global.

A protocol XML doesn't say which interfaces are globals. The rule the
ecosystem follows: an interface is a global if no request or event anywhere
creates it with a typed new_id (wl_registry.bind's untyped new_id is how
globals are made, so it doesn't count). wl_display is the connection itself,
not a global, and is left out; so are the interfaces that only exist for
Xwayland or that are deprecated in favour of a newer version shipped
alongside them, which a compositor is expected to skip.

The output is a C++ header: one table of {protocol, interface, version},
so a compositor's test can check, interface by interface, that it
advertises everything, at the newest version.

usage: wlglobals.py <protocol.xml> [...] -o out.hpp
"""
from __future__ import annotations

import argparse
import os
import sys
import xml.etree.ElementTree as ET

# Superseded by a newer protocol that is generated alongside it, and not
# expected of a new compositor. Each entry says what replaces it.
SUPERSEDED = {
    "wl_shell": "xdg_wm_base",
    "zxdg_shell_v6": "xdg_wm_base",
    "zwp_tablet_manager_v1": "zwp_tablet_manager_v2",
    "zwp_text_input_manager_v1": "zwp_text_input_manager_v3",
    "zxdg_exporter_v1": "zxdg_exporter_v2",
    "zxdg_importer_v1": "zxdg_importer_v2",
    "zwp_linux_explicit_synchronization_v1": "wp_linux_drm_syncobj_manager_v1",
    "zwp_fullscreen_shell_v1": "(kiosk shells only)",
    "zwp_input_method_v1": "(the input-method side, for a compositor with one built in)",
    "zwp_input_panel_v1": "(the input-method side)",
}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("xml", nargs="+")
    ap.add_argument("-o", "--output", required=True)
    args = ap.parse_args()

    ifaces: dict[str, tuple[str, int]] = {}   # name -> (protocol, version)
    created: set[str] = set()
    for path in args.xml:
        root = ET.parse(path).getroot()
        proto = root.get("name", os.path.basename(path))
        for iface in root.findall("interface"):
            ifaces[iface.get("name")] = (proto, int(iface.get("version", "1")))
            for msg in list(iface.findall("request")) + list(iface.findall("event")):
                for arg in msg.findall("arg"):
                    if arg.get("type") == "new_id" and arg.get("interface"):
                        created.add(arg.get("interface"))

    rows = []
    for name, (proto, ver) in sorted(ifaces.items(), key=lambda kv: (kv[1][0], kv[0])):
        if name in created or name == "wl_display":
            continue
        rows.append((proto, name, ver, SUPERSEDED.get(name, "")))

    out = [
        "// GENERATED by wlglobals.py: every global interface in the protocols",
        "// loom was built with, at its newest version. See tools/wlglobals.py.",
        "#pragma once",
        "",
        "#include <array>",
        "#include <cstdint>",
        "#include <string_view>",
        "",
        "namespace i4::wl::proto {",
        "",
        "struct GlobalInfo {",
        "    std::string_view protocol;",
        "    std::string_view interface;",
        "    std::uint32_t version;",
        "    /// Non-empty: superseded by this, and not expected of a new compositor.",
        "    std::string_view superseded_by;",
        "};",
        "",
        f"inline constexpr std::array<GlobalInfo, {len(rows)}> all_globals{{{{",
    ]
    for proto, name, ver, sup in rows:
        out.append(f'    {{"{proto}", "{name}", {ver}, "{sup}"}},')
    out += ["}};", "", "}  // namespace i4::wl::proto", ""]
    with open(args.output, "w") as f:
        f.write("\n".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
